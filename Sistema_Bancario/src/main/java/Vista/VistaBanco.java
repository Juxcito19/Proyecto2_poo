    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        try {
        String numero = txtNumero.getText().trim();
        String titular = txtTitular.getText().trim();

        if (numero.isEmpty() || titular.isEmpty()) {
            txtResultado.setText("Debes ingresar el número de cuenta y el titular.");
            return;
        }

        int dia = Integer.parseInt(txtDia.getText().trim());
        int mes = Integer.parseInt(txtMes.getText().trim());
        int anio = Integer.parseInt(txtAnio.getText().trim());
        double saldoInicial = Double.parseDouble(txtSaldoInicial.getText().trim());

        if (saldoInicial < 0) {
            txtResultado.setText("El saldo inicial no puede ser negativo.");
            return;
        }

        Fecha fecha = new Fecha(dia, mes, anio);
        boolean creada;

        if (cmbTipo.getSelectedItem().toString().equals("Ahorros")) {
            creada = controlador.crearCuentaAhorros(numero, titular, fecha, saldoInicial);
        } else {
            double cupo = Double.parseDouble(txtCupo.getText().trim());
            creada = controlador.crearCuentaCorriente(numero, titular, fecha, saldoInicial, cupo);
        }

        if (creada) {
            txtResultado.setText("Cuenta creada correctamente.");
        } else {
            txtResultado.setText("Ya existe una cuenta con ese número.");
        }
    } catch (NumberFormatException e) {
        txtResultado.setText("Revisa que la fecha, el saldo y el cupo sean números válidos.");
    }
    }//GEN-LAST:event_btnCrearActionPerformed

    private void btnConsignarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsignarActionPerformed
     try {
        String numero = txtNumero.getText().trim();
        double valor = Double.parseDouble(txtValor.getText().trim());

        if (controlador.buscarCuenta(numero) == null) {
            txtResultado.setText("No existe una cuenta con ese número.");
            return;
        }

        if (controlador.consignar(numero, valor)) {
            txtResultado.setText("Consignación realizada.\n" + controlador.consultarSaldo(numero));
        } else {
            txtResultado.setText("El valor a consignar debe ser mayor que 0.");
        }
    } catch (NumberFormatException e) {
        txtResultado.setText("Ingresa un valor válido en la operación.");
    }
    }//GEN-LAST:event_btnConsignarActionPerformed

